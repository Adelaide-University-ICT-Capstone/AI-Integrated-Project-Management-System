// ─── COLOUR HELPERS ───────────────────────────────────────────────────────────

// Maps project status strings to their badge background and text colours.
// Using a lookup object is cleaner than repeated if/else chains and
// makes it easy to add new statuses in one place.
const STATUS_COLOURS: Record<string, { bg: string; text: string }> = {
  Completed:     { bg: "#dcfce7", text: "#16a34a" }, // green
  "In Progress": { bg: "#dbeafe", text: "#2563eb" }, // blue
  Planning:      { bg: "#fef9c3", text: "#ca8a04" }, // amber
}

// Returns a colour based on progress percentage — used for progress bars
// and the circular SVG ring in the project header.
// Green = complete, Blue = on track, Amber = slowing, Red = critical
function progressColor(pct: number) {
  if (pct === 100) return "#22c55e" // green  — complete
  if (pct >= 60)   return "#3b82f6" // blue   — healthy progress
  if (pct >= 30)   return "#f59e0b" // amber  — falling behind
  return "#ef4444"                  // red    — critical
}

// Fixed palette of 8 colours used for worker avatar circles
const AVATAR_PALETTE = [
  "#3b82f6", "#8b5cf6", "#ec4899", "#f97316",
  "#14b8a6", "#6366f1", "#22c55e", "#f43f5e",
]

// Deterministically maps a name string to a colour from AVATAR_PALETTE.
// Uses a polynomial rolling hash (multiplier 31) so the same name always
// produces the same colour without storing preferences anywhere.
// The bitwise AND with 0xffffffff keeps the number within 32-bit range.
function avatarColor(name: string) {
  let h = 0
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) & 0xffffffff
  return AVATAR_PALETTE[Math.abs(h) % AVATAR_PALETTE.length]
}

// ─── CIRCULAR PROGRESS COMPONENT ─────────────────────────────────────────────
// Renders a circular SVG progress ring showing overall project completion.
// Built with raw SVG to avoid adding a charting library dependency.
//
// How it works:
//   - Two <circle> elements are drawn at the same position
//   - The background circle is grey and always full
//   - The progress circle uses strokeDasharray to show only (pct/100) of its circumference
//   - Circumference = 2 * π * radius = 2 * 3.14159 * 42 ≈ 264px
//   - dash = percentage of that circumference to colour in
//   - The SVG is rotated -90deg so progress starts from the top (12 o'clock)
function CircleProgress({ pct }: { pct: number }) {
  const r    = 42                    // radius in pixels
  const circ = 2 * Math.PI * r      // full circumference (~264px)
  const dash = (pct / 100) * circ   // how many pixels of arc to fill
  const color = progressColor(pct)

  return (
    <div style={{ position: "relative", width: 96, height: 96 }}>
      {/* SVG rotated so 0% starts at the top rather than the right */}
      <svg width="96" height="96" style={{ transform: "rotate(-90deg)" }}>
        {/* Background ring — always full grey circle */}
        <circle cx="48" cy="48" r={r} fill="none" stroke="#e5e7eb" strokeWidth="7" />
        {/* Progress arc — length controlled by strokeDasharray */}
        <circle
          cx="48" cy="48" r={r} fill="none"
          stroke={color} strokeWidth="7"
          strokeDasharray={`${dash} ${circ}`} // dash = filled, circ-dash = gap
          strokeLinecap="round"
        />
      </svg>
      {/* Percentage label centred over the ring using absolute positioning */}
      <div style={{
        position: "absolute", inset: 0,
        display: "flex", flexDirection: "column",
        alignItems: "center", justifyContent: "center",
      }}>
        <span style={{ fontSize: 16, fontWeight: 700, color }}>{pct}%</span>
        <span style={{ fontSize: 9, color: "#9ca3af", letterSpacing: "0.04em" }}>Overall Progress</span>
      </div>
    </div>
  )
}

// ─── WORKFORCE ALLOCATION MODAL ───────────────────────────────────────────────
// Popup dialog for adding and removing team members from a project.
//
// Props:
//   workers — the current workforce array for the project
//   onClose — called when the user clicks Cancel or closes the modal
//   onSave  — called with the updated workforce array when Save is clicked
//
// The modal manages its own local copy of the workforce (rows state) so
// changes are only committed to the parent when Save is clicked.
// Clicking Cancel discards all changes made in the modal session.
function AllocationModal({
  workers,
  onClose,
  onSave,
}: {
  workers: ProjectWorker[]
  onClose: () => void
  onSave: (updated: ProjectWorker[]) => void
}) {
  // Local copy of the workforce — edits here don't affect the parent until Save
  const [rows, setRows] = useState<ProjectWorker[]>(workers)

  // Controlled state for the two dropdown selectors
  const [employee, setEmployee] = useState("")
  const [role, setRole]         = useState("")

  // Available role options — in production these would come from GET /api/v1/roles
  const ROLE_OPTIONS = [
    "Project Manager", "Structural Engineer", "Frontend Developer",
    "Backend Developer", "Security Engineer", "Site Supervisor",
    "Landscape Architect", "MEP Engineer",
  ]

  // Available employee options — in production these would come from GET /api/v1/users
  const EMPLOYEE_OPTIONS = [
    "Alice Martin", "Bob Chen", "Charlie Davis", "Diana Ross",
    "Harri Rassias", "Robert Johnson", "Sarah Chen", "Marcus Lee",
  ]

  // Adds a new worker to the local rows array.
  // Guard clause returns early if either dropdown is empty.
  // Date.now() generates a unique numeric ID from the current timestamp —
  // guaranteed unique within a session since time always moves forward.
  // In production, the backend would assign a real UUID on save.
  const handleAdd = () => {
    if (!employee || !role) return // both fields required
    const newRow: ProjectWorker = {
      id: Date.now(), // temporary client-side ID
      name: employee,
      role,
      assignedRole: role,
      status: "active",
    }
    // Spread operator copies all existing rows then appends the new one
    setRows((prev) => [...prev, newRow])
    // Reset dropdowns so the user can add another worker immediately
    setEmployee("")
    setRole("")
  }

  // Removes a worker by filtering out the one with the matching ID.
  // filter() returns a new array excluding the removed worker —
  // React state requires a new array reference to trigger a re-render.
  const handleRemove = (id: number) => setRows((prev) => prev.filter((r) => r.id !== id))

  return (
    // Full-screen semi-transparent overlay — clicking outside doesn't close
    // (intentional — prevents accidental data loss)
    <div style={{
      position: "fixed", inset: 0, zIndex: 50,
      background: "rgba(0,0,0,0.35)",
      display: "flex", alignItems: "center", justifyContent: "center",
    }}>
      {/* Modal card — fixed width, scrollable body */}
      <div style={{
        background: "#fff",
        borderRadius: 12,
        boxShadow: "0 20px 60px rgba(0,0,0,0.18)",
        width: 480,
        maxHeight: "80vh", // prevents modal exceeding viewport on small screens
        display: "flex",
        flexDirection: "column",
        overflow: "hidden",
      }}>

        {/* ── Modal Header ── */}
        <div style={{ padding: "24px 28px 16px" }}>
          <div style={{ fontSize: 18, fontWeight: 700, color: "#111827" }}>
            Workforce Allocation
          </div>
          <div style={{ fontSize: 13, color: "#6b7280", marginTop: 2 }}>
            Increase your team power
          </div>
        </div>

        {/* ── Add Row — Employee + Role dropdowns + Add button ── */}
        <div style={{ display: "flex", gap: 10, padding: "0 28px 16px", alignItems: "center" }}>

          {/* Employee dropdown — controlled by employee state */}
          <select
            value={employee}
            onChange={(e) => setEmployee(e.target.value)}
            style={{
              flex: 1, padding: "9px 12px",
              border: "1px solid #d1d5db", borderRadius: 8,
              fontSize: 13, color: "#374151", background: "#fff",
              outline: "none", cursor: "pointer",
            }}
          >
            <option value="">Employee</option>
            {EMPLOYEE_OPTIONS.map((e) => <option key={e}>{e}</option>)}
          </select>

          {/* Role dropdown — controlled by role state */}
          <select
            value={role}
            onChange={(e) => setRole(e.target.value)}
            style={{
              flex: 1, padding: "9px 12px",
              border: "1px solid #d1d5db", borderRadius: 8,
              fontSize: 13, color: "#374151", background: "#fff",
              outline: "none", cursor: "pointer",
            }}
          >
            <option value="">Role</option>
            {ROLE_OPTIONS.map((r) => <option key={r}>{r}</option>)}
          </select>

          {/* Add button — calls handleAdd which validates both fields first */}
          <button
            onClick={handleAdd}
            style={{
              padding: "9px 20px", background: "#2563eb", color: "#fff",
              border: "none", borderRadius: 8, fontSize: 13,
              fontWeight: 600, cursor: "pointer",
            }}
          >
            Add
          </button>
        </div>

        {/* ── Workers Table ── */}
        {/* Scrollable section — flex: 1 makes it fill remaining modal height */}
        <div style={{ borderTop: "1px solid #f3f4f6", overflowY: "auto", flex: 1 }}>
          <table style={{ width: "100%", borderCollapse: "collapse" }}>
            <thead>
              <tr style={{ background: "#f9fafb" }}>
                <th style={{ padding: "10px 28px", textAlign: "left", fontSize: 12, fontWeight: 600, color: "#6b7280", letterSpacing: "0.03em" }}>
                  Employee Name
                </th>
                <th style={{ padding: "10px 16px", textAlign: "left", fontSize: 12, fontWeight: 600, color: "#6b7280", letterSpacing: "0.03em" }}>
                  Role
                </th>
                <th style={{ width: 40 }} /> {/* Remove button column */}
              </tr>
            </thead>
            <tbody>
              {/* Empty state — shown when no workers have been assigned */}
              {rows.length === 0 ? (
                <tr>
                  <td colSpan={3} style={{ padding: "24px 28px", color: "#9ca3af", fontSize: 13, textAlign: "center" }}>
                    No team members assigned yet
                  </td>
                </tr>
              ) : rows.map((w) => (
                <tr key={w.id} style={{ borderTop: "1px solid #f3f4f6" }}>
                  <td style={{ padding: "11px 28px", fontSize: 13, color: "#374151" }}>{w.name}</td>
                  <td style={{ padding: "11px 16px", fontSize: 13, color: "#374151" }}>{w.assignedRole}</td>
                  <td style={{ padding: "11px 16px", textAlign: "center" }}>
                    {/* Remove button — calls handleRemove with this worker's ID */}
                    <button
                      onClick={() => handleRemove(w.id)}
                      style={{ background: "none", border: "none", color: "#9ca3af", cursor: "pointer", fontSize: 16, lineHeight: 1, padding: "2px 6px" }}
                    >
                      ×
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        {/* ── Modal Footer — Cancel and Save ── */}
        <div style={{ display: "flex", justifyContent: "flex-end", gap: 10, padding: "16px 28px", borderTop: "1px solid #f3f4f6" }}>

          {/* Cancel — closes modal without saving, discarding all local changes */}
          <button
            onClick={onClose}
            style={{ padding: "9px 20px", background: "#fff", border: "1px solid #d1d5db", borderRadius: 8, fontSize: 13, fontWeight: 500, color: "#374151", cursor: "pointer" }}
          >
            Cancel
          </button>

          {/* Save — passes updated rows back to parent via onSave prop, then closes */}
          <button
            onClick={() => { onSave(rows); onClose() }}
            style={{ padding: "9px 20px", background: "#2563eb", border: "none", borderRadius: 8, fontSize: 13, fontWeight: 600, color: "#fff", cursor: "pointer", display: "flex", alignItems: "center", gap: 6 }}
          >
            Save
          </button>
        </div>
      </div>
    </div>
  )
}

