// Base worker — represents any employee in the system
interface Worker {
  id: number
  name: string
  role: string
  status?: "active" | "completed" | "available" // optional — not all contexts need status
}

// ProjectWorker extends Worker with an assignedRole specific to this project.
// The same employee can have different roles on different projects.
interface ProjectWorker extends Worker {
  assignedRole: string
}

// Full project object — contains all data shown in the detail view
interface Project {
  id: string
  code: string
  name: string
  department: string
  location: string
  startDate: string
  deliveryDate: string
  progress: number // 0–100 overall completion percentage
  status: "Completed" | "In Progress" | "Planning"
  aiInsight: { message: string; detail: string; confidence: number }
  tasks: { name: string; progress: number }[]
  materials: { name: string; qty: string; status: "Delivered" | "Pending" | "In Transit" }[]
  workforce: ProjectWorker[]
}

